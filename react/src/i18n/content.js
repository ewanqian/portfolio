function localizeRecord(record, language, dictionary) {
  if (language !== 'en') {
    return record
  }

  const override = dictionary?.en?.[record.id]

  if (!override) {
    return record
  }

  return {
    ...record,
    ...override
  }
}

export function localizeWork(work, language) {
  return localizeRecord(work, language, workTranslations)
}

export function localizeNode(node, language) {
  return localizeRecord(node, language, nodeTranslations)
}

export function localizeWriting(writing, language) {
  return localizeRecord(writing, language, writingTranslations)
}

export function localizeScene(scene, language) {
  return localizeRecord(scene, language, sceneTranslations)
}

export function localizeNetworkItem(item, language) {
  return localizeRecord(item, language, networkTranslations)
}

export function localizeTimelineItem(item, language) {
  return localizeRecord(item, language, timelineTranslations)
}
